"""Structural transport boundary shared by local and native-relay speech."""

from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Any, Protocol

from .client import CanonicalEvent, SessionConfig


class SpeechSession(Protocol):
    metadata: dict[str, Any]

    async def send_audio(self, data: bytes | bytearray | memoryview) -> None: ...
    async def commit_audio(self) -> None: ...
    async def append_text(self, text: str) -> None: ...
    async def commit_text(self) -> None: ...
    async def cancel(self) -> None: ...
    async def finish(self) -> None: ...
    async def aclose(self) -> None: ...
    def events(self) -> AsyncIterator[CanonicalEvent]: ...


class SpeechClient(Protocol):
    async def open(
        self, config: SessionConfig, *, idempotency_key: str | None = None
    ) -> SpeechSession: ...
    async def aclose(self) -> None: ...
